-- Public task data is intentionally readable by the public dashboard.
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  doc_number text,
  issuer text,
  issue_date date,
  deadline date default '2026-12-31',
  level text default 'Trung ương' check (level in ('Trung ương', 'Thành ủy', 'Phường')),
  status text default 'Chưa thực hiện' check (status in ('Chưa thực hiện', 'Đang thực hiện', 'Hoàn thành')),
  assignee text default 'Văn phòng Đảng ủy',
  file_url text,
  doc_url text,
  file_name text,
  is_concretized boolean default false,
  concretized_by text,
  target_name text,
  target_percent numeric default 0,
  sub_targets jsonb default '[]'::jsonb,
  created_at timestamptz default now()
);

create index if not exists tasks_level_idx on public.tasks(level);
create index if not exists tasks_status_idx on public.tasks(status);

-- Keep this column as text for compatibility with existing legacy accounts.
-- Supabase users are linked by storing auth.users.id as text in this column.
create table if not exists public.app_users (
  id text primary key,
  username text not null unique,
  auth_email text unique,
  full_name text not null,
  role text not null check (role in ('viewer', 'editor', 'admin')),
  created_at timestamptz default now()
);

alter table public.app_users add column if not exists auth_email text;
alter table public.app_users drop column if exists password;
create unique index if not exists app_users_auth_email_idx
  on public.app_users (lower(auth_email))
  where auth_email is not null;

