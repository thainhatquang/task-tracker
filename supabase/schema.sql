create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role
  from public.app_users
  where id = auth.uid()::text
     or lower(auth_email) = lower(auth.jwt() ->> 'email')
  limit 1
$$;

create or replace function public.is_app_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.current_app_role() = 'admin', false)
$$;

create or replace function public.is_app_editor()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.current_app_role() in ('editor', 'admin'), false)
$$;

revoke all on function public.current_app_role() from public;
revoke all on function public.is_app_admin() from public;
revoke all on function public.is_app_editor() from public;
grant execute on function public.current_app_role() to authenticated;
grant execute on function public.is_app_admin() to authenticated;
grant execute on function public.is_app_editor() to authenticated;

