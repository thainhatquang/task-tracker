-- Resolve a username to its Supabase Auth email without exposing app_users
-- or passwords to the browser. The API uses this function before sign-in.
create or replace function public.resolve_login_email(login_username text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    nullif(app.auth_email, ''),
    linked_user.email,
    metadata_user.email
  )
  from public.app_users app
  left join auth.users linked_user on linked_user.id::text = app.id
  left join lateral (
    select au.email
    from auth.users au
    where lower(coalesce(
      au.raw_user_meta_data ->> 'username',
      au.raw_user_meta_data ->> 'user_name'
    )) = lower(app.username)
    order by au.created_at
    limit 1
  ) metadata_user on true
  where lower(app.username) = lower(login_username)
     or lower(app.auth_email) = lower(login_username)
  limit 1
$$;

revoke all on function public.resolve_login_email(text) from public;
grant execute on function public.resolve_login_email(text) to anon, authenticated;
